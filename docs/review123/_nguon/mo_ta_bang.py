def describe(table: str, col: str) -> tuple[str, str]:
    key = f"{table}.{col}"
    if key in SPECIFIC:
        return SPECIFIC[key]
    if col in GENERIC:
        return GENERIC[col]
    if col.endswith("_id"):
        ref = col[:-3].replace("_", " ")
        return (f"Reference to the {ref}.", f"Tham chiếu tới {ref}.")
    raise KeyError(f"Thiếu mô tả cho {key}")
